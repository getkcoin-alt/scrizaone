"use client";

// Opt-in AI Search Readiness Check. The visitor checks a site they own or manage.
// Nothing is stored; the report stays in the browser unless the visitor chooses
// to download it or send a summary to the team.
import { useState } from "react";
import { recordEvent } from "@/lib/measurement";
import { company } from "@/lib/site";

const LEVEL = { pass: "Pass", warn: "Improve", fail: "Fix", info: "Info" };

function reportMarkdown(r) {
  const lines = [
    `# AI Search Readiness Check: ${r.url}`,
    ``,
    `Checked: ${new Date(r.checkedAt).toUTCString()} · Score: ${r.score}/100 (${r.grade})`,
    ...(r.capped ? [``, `**${r.capped}**`] : []),
    ``,
    `## Scores`,
    ...r.categories.map((c) => `- ${c.name}: ${c.score}/${c.max}`),
    ``,
    `## Findings`,
  ];
  for (const c of r.categories) {
    lines.push(``, `### ${c.name}`);
    for (const x of r.checks.filter((k) => k.category === c.id)) {
      lines.push(`- [${LEVEL[x.level]}] ${x.title}: ${x.detail}`, `  - Fix: ${x.fix}`);
    }
  }
  lines.push(``, `## Limits`, ...r.limits.map((l) => `- ${l}`), ``, `Generated by the free check at https://www.scrizaone.com/tools/ai-search-readiness`);
  return lines.join("\n");
}

export default function SiteCheck() {
  const [url, setUrl] = useState("");
  const [confirm, setConfirm] = useState(false);
  const [state, setState] = useState({ loading: false, error: "", report: null });

  const run = async (e) => {
    e.preventDefault();
    setState({ loading: true, error: "", report: null });
    recordEvent("site_check_run");
    try {
      const res = await fetch("/api/site-check", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ url, confirm }),
      });
      const data = await res.json().catch(() => ({}));
      if (!res.ok) throw new Error(data.error || "The check could not be completed. Please try again.");
      setState({ loading: false, error: "", report: data });
      recordEvent("site_check_completed");
    } catch (err) {
      setState({ loading: false, error: err.message, report: null });
    }
  };

  const download = () => {
    const r = state.report;
    const blob = new Blob([reportMarkdown(r)], { type: "text/markdown" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = `ai-search-readiness-${new URL(r.url).hostname}.md`;
    a.click();
    URL.revokeObjectURL(a.href);
    recordEvent("site_check_report_exported");
  };

  const askForHelp = () => {
    const r = state.report;
    const top = r.priorities.map((id) => r.checks.find((c) => c.id === id)).filter(Boolean);
    const text = [
      "Hello ScrizaOne, I ran the AI Search Readiness Check and would like help with the fixes.",
      `Site: ${r.url}`,
      `Score: ${r.score}/100 (${r.grade})`,
      "Top items:",
      ...top.map((c, i) => `${i + 1}. ${c.title}: ${c.detail}`),
      "",
      "Sent from scrizaone.com",
    ].join("\n");
    const wa = new URL(company.whatsapp);
    wa.searchParams.set("text", text);
    recordEvent("site_check_help_requested");
    window.location.assign(wa.toString());
  };

  const r = state.report;
  return (
    <div className="site-check">
      <form className="check-form card" onSubmit={run}>
        <label htmlFor="check-url"><strong>Website page to check</strong></label>
        <div className="check-input-row">
          <input id="check-url" type="text" inputMode="url" autoComplete="url" placeholder="example.com or https://example.com/services" value={url} onChange={(e) => setUrl(e.target.value)} required />
          <button className="btn" type="submit" disabled={state.loading || !confirm}>{state.loading ? "Checking…" : "Run free check"}</button>
        </div>
        <label className="check-confirm">
          <input type="checkbox" checked={confirm} onChange={(e) => setConfirm(e.target.checked)} />
          <span>I own or manage this website, or have permission to check it.</span>
        </label>
        <p className="small muted">We load the page, robots.txt, llms.txt and your sitemap once, like a browser would. Nothing is saved, and no email is needed.</p>
      </form>

      <div aria-live="polite">
        {state.loading && <p className="notice">Checking the page, robots.txt, llms.txt and sitemap. This usually takes a few seconds…</p>}
        {state.error && <p className="notice check-error" role="alert">{state.error}</p>}
      </div>

      {r && (
        <section className="check-report" aria-labelledby="report-h">
          <div className="check-summary card">
            <div className="check-score" aria-label={`Score ${r.score} out of 100`}>
              <span className="check-score-num">{r.score}</span><span className="check-score-of">/100</span>
              <span className={`check-grade g-${r.score >= 85 ? "a" : r.score >= 65 ? "b" : r.score >= 45 ? "c" : "d"}`}>{r.grade}</span>
            </div>
            <div className="check-summary-body">
              <h2 id="report-h">Report for {new URL(r.url).hostname}</h2>
              <p className="small muted">{r.url} · checked {new Date(r.checkedAt).toLocaleString()}</p>
              {r.capped && <p className="notice check-error">{r.capped}</p>}
              <ul className="check-bars">
                {r.categories.map((c) => (
                  <li key={c.id}>
                    <span>{c.name}</span>
                    <span className="check-bar" aria-hidden="true"><span style={{ width: `${Math.round((c.score / c.max) * 100)}%` }} /></span>
                    <span className="check-bar-val">{c.score}/{c.max}</span>
                  </li>
                ))}
              </ul>
              <div className="cta-row">
                <button type="button" className="btn btn-sm" onClick={download}>Download report (.md)</button>
                <button type="button" className="btn btn-sm btn-ghost" onClick={() => { document.querySelectorAll(".check-item").forEach((d) => { d.open = true; }); window.print(); }}>Print / save as PDF</button>
              </div>
            </div>
          </div>

          {r.priorities.length > 0 && (
            <div className="card check-priorities">
              <h3>Fix these first</h3>
              <ol>
                {r.priorities.map((id) => {
                  const c = r.checks.find((x) => x.id === id);
                  return <li key={id}><strong>{c.title}.</strong> {c.fix}</li>;
                })}
              </ol>
            </div>
          )}

          <div className="card">
            <h3>Who can read this page</h3>
            <div className="table-scroll">
              <table className="table">
                <thead><tr><th>Crawler</th><th>Used by</th><th>robots.txt</th></tr></thead>
                <tbody>
                  {r.bots.map((b) => (
                    <tr key={b.ua}><td><code>{b.ua}</code></td><td>{b.who}</td><td>{b.allowed ? "Allowed" : <strong>Blocked</strong>}</td></tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>

          {r.categories.map((cat) => (
            <div key={cat.id} className="check-group">
              <h3>{cat.name} <span className="muted small">{cat.score}/{cat.max}</span></h3>
              {r.checks.filter((x) => x.category === cat.id).map((x) => (
                <details key={x.id} className={`check-item lvl-${x.level}`} open={x.level === "fail"}>
                  <summary><span className="check-badge">{LEVEL[x.level]}</span>{x.title}{x.max > 0 && <span className="muted small"> · {x.points}/{x.max}</span>}</summary>
                  <p>{x.detail}</p>
                  <p><strong>What to do:</strong> {x.fix}</p>
                </details>
              ))}
            </div>
          ))}

          <div className="card flat">
            <h3>What this check can't tell you</h3>
            <ul className="ticks">{r.limits.map((l) => <li key={l}>{l}</li>)}</ul>
          </div>

          <div className="card check-help">
            <h3>Want help fixing this?</h3>
            <p>Send this summary to our team on WhatsApp. You'll review the message before sending. We quote per milestone, in your currency, after a free call. {company.replyRule}</p>
            <button type="button" className="btn" onClick={askForHelp}>Send summary on WhatsApp</button>
          </div>
        </section>
      )}
    </div>
  );
}
